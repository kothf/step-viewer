// Service worker for offline start (FRS FR-STO-030). After the build, writes sw.js into the output
// folder with the list of app files to precache (the full OpenCASCADE wasm is cached the first time
// it loads instead: it is 50 MB and only needed for modelling and exact geometry). The cache name
// carries the version and a hash of the file list, so each build gets its own cache and drops the old.
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const SKIP = new Set(["sw.js", "LICENSE", "VERSION", "THIRD-PARTY-LICENSES.txt", "occt/opencascade.full.wasm"]);

function walk(dir, root, out) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) { if (n !== "samples") walk(p, root, out); continue; }
    const rel = relative(root, p).split(sep).join("/");
    if (!SKIP.has(rel) && !rel.endsWith(".map")) out.push([rel, statSync(p).size]);
  }
  return out;
}

const worker = (cache, files) => `// Generated by scripts/sw-plugin.mjs: offline start (FR-STO-030).
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};
const at = u => new URL(u, self.registration.scope).href;
const own = new Set(FILES.map(at));

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(at(u), { cache: "reload" })))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("mobiuscad-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  const scope = self.registration.scope;
  if (!url.href.startsWith(scope)) return;
  const key = url.origin + url.pathname;
  const page = req.mode === "navigate" || key === scope || key === at("index.html");
  if (page) {
    // The page: network first (new versions show at once), the cached one offline.
    e.respondWith(fetch(req).then(r => {
      if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(at("index.html"), copy)); }
      return r;
    }).catch(() => caches.match(at("index.html"))));
    return;
  }
  // App files and the OpenCASCADE builds: cache first. Anything else (opened models) goes to the network.
  if (!own.has(key) && !key.startsWith(at("occt/"))) return;
  e.respondWith(caches.match(key).then(hit => hit || fetch(req).then(r => {
    if (r.ok && r.status === 200) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(key, copy)); }
    return r;
  })));
});
`;

export default function sw({ version }) {
  let outDir = "dist";
  return {
    name: "mobiuscad-sw",
    apply: "build",
    configResolved(c) { outDir = resolve(c.root, c.build.outDir); },
    closeBundle() {
      const files = walk(outDir, outDir, []).sort((a, b) => (a[0] < b[0] ? -1 : 1));
      const hash = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 10);
      writeFileSync(join(outDir, "sw.js"), worker(`mobiuscad-${version}-${hash}`, files.map(f => f[0])));
    },
  };
}
