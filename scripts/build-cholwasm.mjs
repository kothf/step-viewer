// Builds the factorisation kernel (native/chol-kernel/kernel.c) into src/sim/cholKernel.wasm.ts: two WebAssembly
// modules as base64, one importing a shared memory and one a plain memory. Needs clang with the wasm32 target and
// wasm-ld (Ubuntu: clang lld). The result is committed, so a normal build needs neither.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const src = "native/chol-kernel/kernel.c", tmp = mkdtempSync(join(tmpdir(), "cholwasm-"));
const base = ["--target=wasm32", "-O3", "-msimd128", "-nostdlib", "-fno-builtin", "-Wl,--no-entry", "-Wl,--import-memory", "-Wl,--strip-all", "-Wl,-z,stack-size=16384"];
const build = (name, extra) => {
  const out = join(tmp, name);
  execFileSync("clang", [...base, ...extra, "-o", out, src], { stdio: "inherit" });
  return readFileSync(out);
};
const shared = build("shared.wasm", ["-matomics", "-mbulk-memory", "-Wl,--shared-memory", "-Wl,--max-memory=4294967296"]);
const plain = build("plain.wasm", []);
const lines = s => s.toString("base64").match(/.{1,120}/g).map(l => `  "${l}"`).join(" +\n");
writeFileSync("src/sim/cholKernel.wasm.ts",
  `// Generated by scripts/build-cholwasm.mjs from native/chol-kernel/kernel.c. Do not edit.\n` +
  `/** The factorisation kernel importing a shared memory (base64). */\nexport const KERNEL_SHARED =\n${lines(shared)};\n` +
  `/** The same importing a plain memory (base64). */\nexport const KERNEL_PLAIN =\n${lines(plain)};\n`);
console.log(`cholKernel.wasm.ts: shared ${shared.length} bytes, plain ${plain.length} bytes`);
